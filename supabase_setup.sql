create table if not exists public.movies (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'Other',
  release_year integer,
  poster_url text,
  download_url text not null,
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade
);

alter table public.movies enable row level security;
alter table public.admin_users enable row level security;

-- Everyone can view published movie listings.
drop policy if exists "Public can read movies" on public.movies;
create policy "Public can read movies" on public.movies
for select to anon, authenticated using (true);

-- Only user IDs manually added to admin_users can manage listings.
drop policy if exists "Admins can insert movies" on public.movies;
create policy "Admins can insert movies" on public.movies
for insert to authenticated
with check (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "Admins can update movies" on public.movies;
create policy "Admins can update movies" on public.movies
for update to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()))
with check (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "Admins can delete movies" on public.movies;
create policy "Admins can delete movies" on public.movies
for delete to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

-- Admins can see their own admin record. Add admin records using the SQL Editor.
drop policy if exists "Admins can read own admin record" on public.admin_users;
create policy "Admins can read own admin record" on public.admin_users
for select to authenticated using (user_id = auth.uid());
